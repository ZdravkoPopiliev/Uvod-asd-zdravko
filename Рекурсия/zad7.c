/*Решете задачата „Ханойски кули“. Дадени са три кули — A, B и C.
На кула A има n диска с различни размери, наредени един върху друг, като най-големият е най-долу.
Преместете всички дискове от кула A на кула C с помощта на кула B, като спазвате две правила: 
(1) на един ход се премества само един диск — най-горният на някоя от кулите; 
(2) по-голям диск никога не се поставя върху по-малък. 
Напишете рекурсивна функция hanoi(n, from, to, via), 
която извежда всяко преместване на отделен ред във вида „Диск 1: A -> C“. 
Подсказка: базов случай е n = 1 (един диск се мести директно); 
при n > 1 първо се преместват n − 1 диска от from на via, после най-големият диск от from на to,
и накрая n − 1 диска от via на to. Примерен вход: n = 3 => Изход: 7 реда — Диск 1: A -> C;
Диск 2: A -> B; Диск 1: C -> B; Диск 3: A -> C; Диск 1: B -> A; Диск 2: B -> C; Диск 1: A -> C. 
Определете колко са преместванията за n диска. 
Намерете формулата и я проверете за n = 1, 2, 3 и 4 (съответно 1, 3, 7 и 15 премествания).*/

#include <stdio.h>

void hanoi(int n, char from, char to, char via){
    if(n==1){
        printf("Disk 1: %c -> %c\n", from, to);
        return;
    }

    hanoi(n-1, from, via, to);
    printf("Disk %d: %c -> %c\n",n,from,to);
    hanoi(n-1, via, to, from);

}

int main(){
    printf("Input n elemnts: ");
    int n;
    scanf("%d", &n);
    int res=1;
    for(int i=0; i<n; i++){
        res=2*res;
    }
    printf("Izhod: %d\n", res-1);
    hanoi(n, 'A', 'C', 'B');
    return 0;
}